# gmul matrix multiplication
def matrix_mul(A, B):
    result = [[0] * 4 for _ in range(4)]
    for i in range(4):
        for j in range(4):
            for k in range(4):
                result[i][j] ^= gmul(A[i][k], B[k][j])
    return result

# Calculate Inverse Matrix Using Gauss Jordan Elimination
def matrix_inv(A):
    n = 4
    augmented = [row + [1 if i == j else 0 for j in range(n)] for i, row in enumerate(A)]
    
    for col in range(n):
        pivot = -1
        for row in range(col, n):
            if augmented[row][col] != 0:
                pivot = row
                break
        if pivot == -1:
            raise ValueError("Matrix is not invertible.")
        
        augmented[col], augmented[pivot] = augmented[pivot], augmented[col]
        
        pivot_val = augmented[col][col]
        inv_pivot = ginv[pivot_val]
        for j in range(2 * n):
            augmented[col][j] = gmul(augmented[col][j], inv_pivot)
        
        for row in range(n):
            if row != col:
                factor = augmented[row][col]
                for j in range(2 * n):
                    augmented[row][j] ^= gmul(factor, augmented[col][j])
    
    inverse = [row[n:] for row in augmented]
    return inverse

