# This defines multiplication in the Galois Field of size 2^8 with modulus x^8 + x^4 + x^3 + x + 1
MODULUS = 0x1B
def gmul(a, b):
    result = 0
    for _ in range(8):
        if b & 1:
            result ^= a
        b >>= 1

        carry = a & 0x80
        a <<= 1
        a %= 2**8

        if carry:
            a ^= MODULUS

    return result

