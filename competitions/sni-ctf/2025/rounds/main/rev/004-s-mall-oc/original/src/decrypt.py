def xtime(x: int) -> int:
    return ((x << 1) ^ 0x1B) & 0xFF if (x & 0x80) else (x << 1) & 0xFF


def gf_mul(a: int, b: int) -> int:
    res = 0
    while b:
        if b & 1:
            res ^= a
        a = xtime(a)
        b >>= 1
    return res & 0xFF

def InvSubBytes(s):
    for r in range(4):
        for c in range(4):
            s[r][c] = TIGRIS_INV_SBOX[s[r][c]]


def InvReversibleShiftRows(s):
    for r in range(1, 4):
        shift = 2 % 4
        tmp = [s[r][(c - shift) % 4] for c in range(4)]
        for c in range(4):
            s[r][c] = tmp[c]


def ShiftingMixColumn(s, round_idx):
    base = [0x03, 0x04, 0x01, 0x07]
    rot = round_idx & 3
    coef = [base[(i + rot) % 4] for i in range(4)]

    for c in range(4):
        a0, a1, a2, a3 = s[0][c], s[1][c], s[2][c], s[3][c]
        res0 = (
            gf_mul(coef[0], a0)
            ^ gf_mul(coef[1], a1)
            ^ gf_mul(coef[2], a2)
            ^ gf_mul(coef[3], a3)
        )
        res1 = (
            gf_mul(coef[3], a0)
            ^ gf_mul(coef[0], a1)
            ^ gf_mul(coef[1], a2)
            ^ gf_mul(coef[2], a3)
        )
        res2 = (
            gf_mul(coef[2], a0)
            ^ gf_mul(coef[3], a1)
            ^ gf_mul(coef[0], a2)
            ^ gf_mul(coef[1], a3)
        )
        res3 = (
            gf_mul(coef[1], a0)
            ^ gf_mul(coef[2], a1)
            ^ gf_mul(coef[3], a2)
            ^ gf_mul(coef[0], a3)
        )
        s[0][c], s[1][c], s[2][c], s[3][c] = res0, res1, res2, res3


def InvShiftingMixColumn(s, round_idx):
    # In C they applied ShiftingMixColumn 3 times to invert; we replicate that.
    for _ in range(3):
        ShiftingMixColumn(s, round_idx)


def AddRoundKey(s, roundKey):
    # roundKey is bytes-like of length 16
    for c in range(4):
        for r in range(4):
            s[r][c] ^= roundKey[c * 4 + r]


def KeyExpansion128(key16: bytes) -> bytearray:
    Pw = 0xB7E15163
    Qw = 0x9E377969
    roundKeys = bytearray(ROUND_KEY_BYTES)
    roundKeys[0:16] = key16
    bytesGenerated = 16
    rcon = 1
    i = 1
    while bytesGenerated < ROUND_KEY_BYTES:
        temp = bytearray(roundKeys[bytesGenerated - 4 : bytesGenerated])
        if (bytesGenerated % 16) == 0:
            # RotWord
            temp = bytearray([temp[1], temp[2], temp[3], temp[0]])
            # SubWord
            for j in range(4):
                temp[j] = TIGRIS_SBOX[temp[j]]
            word = (temp[0] << 24) | (temp[1] << 16) | (temp[2] << 8) | temp[3]
            mix = Pw if (i & 1) else Qw
            word ^= (mix ^ (rcon << 24)) & 0xFFFFFFFF
            temp = bytearray(
                [
                    (word >> 24) & 0xFF,
                    (word >> 16) & 0xFF,
                    (word >> 8) & 0xFF,
                    word & 0xFF,
                ]
            )
            rcon = (rcon << 1) & 0xFFFFFFFF
            i += 1
        for j in range(4):
            roundKeys[bytesGenerated] = roundKeys[bytesGenerated - 16] ^ temp[j]
            bytesGenerated += 1
    return roundKeys


def load_state(in_bytes):
    s = [[0] * 4 for _ in range(4)]
    for c in range(4):
        for r in range(4):
            s[r][c] = in_bytes[c * 4 + r]
    return s


def store_state(s):
    out = bytearray(16)
    for c in range(4):
        for r in range(4):
            out[c * 4 + r] = s[r][c]
    return bytes(out)

def Tigris_DecryptBlock(in_block: bytes, roundKeys: bytes) -> bytes:
    s = load_state(in_block)
    AddRoundKey(s, roundKeys[ROUNDS*16:(ROUNDS+1)*16])
    for round in range(ROUNDS, 0, -1):
        if round != ROUNDS:
            InvShiftingMixColumn(s, round-1)
        InvReversibleShiftRows(s)
        InvSubBytes(s)
        AddRoundKey(s, roundKeys[(round-1)*16:round*16])
    return store_state(s)

def Tigris_Decrypt(data: bytes, roundKeys: list) -> bytes:
    assert len(data) % 16 == 0
    blocks = len(data) // 16
    out = bytearray(len(data))

    for i in range(blocks):
        b = data[i*16:(i+1)*16]
        out[i*16:(i+1)*16] = Tigris_DecryptBlock(b, roundKeys)

    return bytes(out)

def Tigris_Decrypt_ECB(key: bytes, ciphertext: bytes) -> bytes:
    # Expand key like encryption
    roundKeys = KeyExpansion128(key)
    return Tigris_Decrypt(ciphertext, roundKeys)


